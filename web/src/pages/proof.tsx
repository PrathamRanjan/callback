import { useState } from "react";
import { Link } from "react-router-dom";
import { Download, FlaskConical } from "lucide-react";
import { Tabs, TabsList, TabsTrigger } from "@/components/ui/tabs";
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from "@/components/ui/table";
import { ActButton, Empty, ErrorState, Kpi, PageHead, Panel, Rows, Section, StateChip } from "@/components/app/bits";
import { money, when } from "@/lib/format";
import { useData, useSession, useTitle } from "@/lib/hooks";

interface Sum { arm: string; cases: number; correct: number; traps: number; traps_caught: number; naive_usd: number; ours_usd: number; cost_usd: number; p50_ms: number; p95_ms: number }
interface Proof {
  calls_ended: number; collected_cents: number; breaches_refused: number; quarantined: number;
  trace: { steps: number; runs: number; paypal: number; blocked: number }; chain: { ok: boolean; rows: number };
  model: { label: string; usage: any };
  backtest: { cases: number; run: number; wait: number; deny: number; collected_auto_cents: number; minutes_saved: number; breaches_prevented: number };
  evals: { personas: Sum[]; adversarial: Sum[]; persona_cases: number; attack_cases: number };
  runs: { id: string; subject: string; actor: string; agent_id: string | null; steps: number; paypal_calls: number; blocked: number; status: string; started_at: string }[];
  app_url: string;
}
interface Evals { suite: string; summary: Sum[]; rows: { case_id: string; arm: string; expected: string; actual: string; correct: boolean; kind: string | null; naive_cents: number; ours_cents: number }[] }

function SumTable({ sums, suite }: { sums: Sum[]; suite: string }) {
  if (!sums.length) return <Empty title="Not run yet">Run the suite to fill this in.</Empty>;
  return (
    <Panel className="overflow-x-auto">
      <Table>
        <TableHeader><TableRow><TableHead>Brain</TableHead><TableHead className="text-right">Cases</TableHead><TableHead className="text-right">{suite === "personas" ? "Clean" : "Blocked"}</TableHead><TableHead className="text-right">Traps caught</TableHead><TableHead className="text-right">Model cost</TableHead><TableHead className="text-right">p50</TableHead></TableRow></TableHeader>
        <TableBody>
          {sums.map((s) => (
            <TableRow key={s.arm}>
              <TableCell className="font-medium">{s.arm}</TableCell>
              <TableCell className="text-right num">{s.cases}</TableCell>
              <TableCell className="text-right num">{s.correct}/{s.cases}</TableCell>
              <TableCell className="text-right num">{s.traps ? `${s.traps_caught}/${s.traps}` : "—"}</TableCell>
              <TableCell className="text-right num">${s.cost_usd.toFixed(2)}</TableCell>
              <TableCell className="text-right num">{s.p50_ms ? `${(s.p50_ms / 1000).toFixed(1)} s` : "—"}</TableCell>
            </TableRow>
          ))}
        </TableBody>
      </Table>
    </Panel>
  );
}

export default function ProofPage() {
  useTitle("Proof");
  const { session } = useSession();
  const owner = session?.me?.role === "owner";
  const { data: p, error, loading, reload } = useData<Proof>("/api/app/proof");
  const [suite, setSuite] = useState("personas");
  const [onlyWrong, setOnlyWrong] = useState(true);
  const ev = useData<Evals>(`/api/app/evals?suite=${suite}${onlyWrong ? "&outcome=wrong" : ""}`);
  if (error && !p) return <ErrorState error={error} retry={reload} />;
  if (loading && !p) return <Rows n={5} />;
  if (!p) return null;
  const sums = suite === "personas" ? p.evals.personas : p.evals.adversarial;
  return (
    <>
      <PageHead
        title="Proof"
        happened={`${p.calls_ended} calls finished, ${money(p.collected_cents)} collected, ${p.breaches_refused} unsafe moves refused by the gate.`}
        next={`Every number below is generated by this build: ${p.evals.persona_cases} scripted customers and ${p.evals.attack_cases} attacks, run on demand.`}
      />
      <div className="mb-8 grid grid-cols-2 gap-3 lg:grid-cols-4" data-tour="proof">
        <Kpi label="Tool steps traced" value={p.trace.steps} hint={`${p.trace.runs} runs · ${p.trace.paypal} PayPal calls`} />
        <Kpi label="Blocked by the gate" value={p.trace.blocked} s="off" hint={`${p.quarantined} instruction-like lines ignored`} />
        <Kpi label="Audit chain" value={p.chain.ok ? "Intact" : "Broken"} s={p.chain.ok ? "done" : "off"} hint={`${p.chain.rows} entries`} />
        <Kpi label="AI model" value={<span className="text-[1.1rem]">{p.model.label}</span>} hint={p.model.usage?.calls ? `${p.model.usage.calls} calls · $${Number(p.model.usage.cost_usd ?? 0).toFixed(2)}` : "usage shown after calls"} />
      </div>
      <Section
        id="evals"
        title="Evals"
        hint="The same scripted customers against the rules brain, the AI model brain and an oracle. A clean outcome means the right money result with no rule broken."
        actions={
          owner ? (
            <div className="flex flex-wrap gap-2">
              <ActButton path="/ops/eval/run" fields={{ suite, limit: suite === "personas" ? "12" : "" }} variant="outline" icon={<FlaskConical />} onDone={() => { void reload(); void ev.reload(); }}>{suite === "personas" ? "Run 12 now" : "Run all attacks"}</ActButton>
              <a className="inline-flex h-10 items-center gap-1.5 rounded-md border border-line px-3 text-sm font-medium hover:bg-surface-2" href={`/ops/eval.csv?suite=${suite}`}><Download className="size-4" />CSV</a>
              <a className="inline-flex h-10 items-center gap-1.5 rounded-md border border-line px-3 text-sm font-medium hover:bg-surface-2" href={`/ops/eval/${suite}.md`}>Markdown</a>
            </div>
          ) : null
        }
      >
        <Tabs value={suite} onValueChange={setSuite} className="mb-3">
          <TabsList className="bg-surface-2"><TabsTrigger value="personas" className="min-h-10">Customers ({p.evals.persona_cases})</TabsTrigger><TabsTrigger value="adversarial" className="min-h-10">Attacks ({p.evals.attack_cases})</TabsTrigger></TabsList>
        </Tabs>
        <SumTable sums={sums} suite={suite} />
        <div className="mt-4 flex items-center gap-2">
          <h3 className="text-sm font-semibold">{onlyWrong ? "Cases that went wrong" : "All cases"}</h3>
          <button type="button" className="text-sm font-medium text-brand underline-offset-4 hover:underline" onClick={() => setOnlyWrong(!onlyWrong)}>{onlyWrong ? "Show all" : "Only the wrong ones"}</button>
        </div>
        {ev.data?.rows.length ? (
          <Panel className="mt-2 max-h-[420px] overflow-auto">
            <Table>
              <TableHeader><TableRow><TableHead>Case</TableHead><TableHead>Brain</TableHead><TableHead>Expected</TableHead><TableHead>Got</TableHead><TableHead>Kind</TableHead></TableRow></TableHeader>
              <TableBody>{ev.data.rows.slice(0, 80).map((r, i) => <TableRow key={i}><TableCell className="font-mono text-xs">{r.case_id}</TableCell><TableCell>{r.arm}</TableCell><TableCell>{r.expected}</TableCell><TableCell><StateChip s={r.correct ? "done" : "off"}>{r.actual}</StateChip></TableCell><TableCell className="text-ink-2">{r.kind ?? ""}</TableCell></TableRow>)}</TableBody>
            </Table>
          </Panel>
        ) : <p className="mt-2 text-sm text-ink-2">{ev.loading ? "Loading…" : onlyWrong ? "None went wrong in the last run." : "No rows yet."}</p>}
      </Section>
      <Section id="backtest" title="Replay of your history" hint="Past calls run again through today's rules and limits.">
        <div className="grid grid-cols-2 gap-3 lg:grid-cols-4">
          <Kpi label="Would run alone" value={p.backtest.run} s="done" hint={`of ${p.backtest.cases}`} />
          <Kpi label="Would wait for you" value={p.backtest.wait} s="hold" />
          <Kpi label="Breaches prevented" value={p.backtest.breaches_prevented} s="off" />
          <Kpi label="Minutes saved" value={p.backtest.minutes_saved} />
        </div>
      </Section>
      <Section id="runs" title="Agent runs" hint="Every run, with each tool call, gate decision and PayPal debug id.">
        {p.runs.length ? (
          <ul className="divide-y divide-line overflow-hidden rounded-[10px] border border-line bg-surface">
            {p.runs.slice(0, 20).map((r) => (
              <li key={r.id}>
                <Link to={`/trace/${r.id}`} className="flex flex-wrap items-center gap-3 px-4 py-3 hover:bg-surface-2">
                  <span className="lamp" data-s={r.blocked ? "hold" : r.status === "error" ? "off" : "done"} aria-hidden="true" />
                  <span className="min-w-0 flex-1"><span className="font-medium">{r.subject}</span> <span className="text-sm text-ink-2">· {r.actor}{r.agent_id ? ` · ${r.agent_id}` : ""}</span></span>
                  <span className="text-xs text-ink-2 num">{r.steps} steps · {r.paypal_calls} PayPal · {r.blocked} blocked · {when(r.started_at)}</span>
                </Link>
              </li>
            ))}
          </ul>
        ) : <Empty title="No runs yet" />}
      </Section>
      <Section id="agents" title="For other agents" hint="Another AI agent can use Callback through MCP, through the same gate.">
        <Panel className="space-y-2 p-4 text-sm">
          <p>Owner MCP: <code className="font-mono text-xs">POST {p.app_url}/mcp</code> with the owner key as a Bearer token. Customer MCP: <code className="font-mono text-xs">/c/&lt;token&gt;/mcp</code>.</p>
          <p className="flex flex-wrap gap-3"><a className="font-medium text-brand underline underline-offset-4" href="/llms.txt">llms.txt</a><a className="font-medium text-brand underline underline-offset-4" href="/skill.md">skill.md</a></p>
        </Panel>
      </Section>
    </>
  );
}
